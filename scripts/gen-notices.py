#!/usr/bin/env python3
"""Regenerate the Go-module section of THIRD_PARTY_NOTICES.

Lists every module compiled into the gocode binary (go list -deps of
./cmd/gocode) with its version and license, followed by the full license
texts (and NOTICE files, where a module ships one). Everything between the
BEGIN/END markers is replaced; the rest of the file is kept.

    python3 scripts/gen-notices.py      # run from the repository root
"""

import os
import subprocess
import sys

BEGIN = "<!-- BEGIN GO MODULES (generated by scripts/gen-notices.py; do not edit) -->"
END = "<!-- END GO MODULES -->"
LICENSE_NAMES = ["LICENSE", "LICENSE.txt", "LICENSE.md", "LICENCE", "COPYING", "LICENSE-MIT"]
NOTICE_NAMES = ["NOTICE", "NOTICE.txt", "NOTICE.md"]


def kind(text):
    if "Permission is hereby granted, free of charge" in text:
        return "MIT"
    if "Apache License" in text:
        return "Apache-2.0"
    if "Neither the name" in text:
        return "BSD-3-Clause"
    if "Redistributions of source code" in text:
        return "BSD-2-Clause"
    if "Mozilla Public License" in text:
        return "MPL-2.0"
    if "Permission to use, copy, modify, and/or distribute" in text:
        return "ISC"
    return "see text"


def first_file(directory, names):
    for name in names:
        path = os.path.join(directory, name)
        if os.path.isfile(path):
            with open(path, encoding="utf-8", errors="replace") as f:
                return f.read().strip()
    return None


def main():
    out = subprocess.run(
        ["go", "list", "-deps", "-f",
         "{{if .Module}}{{if not .Module.Main}}{{.Module.Path}}|{{.Module.Version}}|{{.Module.Dir}}{{end}}{{end}}",
         "./cmd/gocode"],
        check=True, capture_output=True, text=True).stdout
    modules = sorted({tuple(line.split("|")) for line in out.splitlines() if line.strip()})

    rows, texts = [], []
    for path, version, directory in modules:
        lic = first_file(directory, LICENSE_NAMES)
        if lic is None:
            sys.exit(f"gen-notices: no license file found for {path} {version}")
        rows.append(f"- {path} {version} ({kind(lic)})")
        block = f"--- {path} {version} ---\n\n{lic}\n"
        notice = first_file(directory, NOTICE_NAMES)
        if notice:
            block += f"\nNOTICE:\n\n{notice}\n"
        texts.append(block)

    section = "\n".join([
        BEGIN,
        "",
        "Go modules compiled into the gocode binary",
        "==========================================",
        "",
        *rows,
        "",
        "License texts",
        "-------------",
        "",
        "\n".join(texts).rstrip(),
        "",
        END,
    ])

    with open("THIRD_PARTY_NOTICES", encoding="utf-8") as f:
        current = f.read()
    if BEGIN in current and END in current:
        head, rest = current.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
        updated = head + section + tail
    else:
        updated = current.rstrip() + "\n\n" + section + "\n"
    with open("THIRD_PARTY_NOTICES", "w", encoding="utf-8") as f:
        f.write(updated)
    print(f"gen-notices: {len(modules)} modules written to THIRD_PARTY_NOTICES")


if __name__ == "__main__":
    main()
